/* 실행: node daon-city/tests/engine-check.js — 규칙·저장 왕복의 작은 회귀 검사 */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const ctx = vm.createContext({}); ctx.window = ctx;
for (const file of ['data.js', 'engine.js']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js', file), 'utf8'), ctx);
const D = ctx.DAON_CITY, E = ctx.DaonEngine;
const plain = value => JSON.parse(JSON.stringify(value));
const s = E.newGame();
assert.equal(s.money, D.rules.startMoney);
assert.equal(E.place(s, 'port', 28).ok, true);
assert.equal(E.place(s, 'textile', 21).ok, true);
assert.equal(E.place(s, 'school', 2).ok, true);
assert.equal(E.exportOf(s, 21), 6);
assert.equal(E.slotsLeft(s), 0);
const before = plain(s);
assert.equal(E.place(s, 'house', 3).ok, false);
assert.deepEqual(plain(s), before);
assert.equal(E.undo(s, 2).ok, true);
assert.equal(s.money, before.money + D.buildings.school.cost);
assert.equal(E.place(s, 'school', 2).ok, true);
const money=s.money, tech=s.tech, r=E.advance(s);
assert.equal(s.money, money + D.rules.income.base + Math.round(6*D.rules.income.exportRate));
assert.equal(s.tech, tech+1);
assert.equal(r.match, true);
assert.equal(r.gauges.econ, 84);
assert.equal(r.gauges.env, 75);
assert.equal(r.gauges.fair, 52);
assert.equal(r.gauges.life, 52);
assert.equal(r.problem, null);
E.applyFx(s, D.eras[0].event.a.fx, D.eras[0].event.a.label);
assert.equal(s.records[0].choices.length, 1);
assert.equal(E.gauges(s).env, 72);
const restored=plain(s);
assert.deepEqual(plain(E.gauges(restored)), plain(E.gauges(s)));
assert.equal(E.nextDecade(restored), true);
assert.equal(restored.d,1);
assert.equal(E.slotsLeft(restored),D.rules.buildsPerDecade[1]);
const powered=E.newGame();powered.d=1;powered.money=100;
assert.equal(E.place(powered,'power',2).ok,true);
assert.equal(E.place(powered,'steel',3).ok,true);
assert.equal(E.undo(powered,2).reason,'power');
assert.equal(E.place(powered,'park',4).ok,true);
assert.equal(E.pollutionAt(powered,3),3);
assert.equal(E.undo(powered,4).ok,true);
assert.equal(E.pollutionAt(powered,3),4);
const priority=E.newGame();priority.money=100;priority.d=1;
E.place(priority,'power',2);E.place(priority,'steel',3);E.place(priority,'chem',28);
const problem=E.advance(priority).problem;
assert.equal(problem.id,'pollution');
assert.equal(priority.problemsSeen.pollution,1);
console.log('PASS: 배치·수출 배율·생산·게이지·공원·발전소 보호·사건 우선순위·저장 왕복');
